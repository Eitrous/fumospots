// The Shannan standard-map feature continues west from the South Tibet edge
// along the already-rendered China-Bhutan boundary. Stop at its eastern join
// so the official overlay does not draw a second, slightly offset copy of that
// existing national boundary. Index 387 is the reviewed source vertex
// [91.562854, 27.8148476] immediately adjacent to the PMTiles join point.
const SOUTH_TIBET_BHUTAN_JOIN_INDEX = 387

export const SOUTH_TIBET_OFFICIAL_COUNTRY_BOUNDARIES: GeoJSON.FeatureCollection<
  GeoJSON.MultiLineString,
  { id: number, name: string }
> = {
  ...SOUTH_TIBET_OFFICIAL_COUNTRY_BOUNDARIES_RAW,
  features: SOUTH_TIBET_OFFICIAL_COUNTRY_BOUNDARIES_RAW.features.map((feature) => {
    if (feature.properties.id !== 128) {
      return feature
    }

    return {
      ...feature,
      geometry: {
        ...feature.geometry,
        coordinates: feature.geometry.coordinates.map((line, index) => (
          index === 0
            ? line.slice(0, SOUTH_TIBET_BHUTAN_JOIN_INDEX + 1)
            : line
        ))
      }
    }
  })
}
